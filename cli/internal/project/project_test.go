func TestFindWalksUp(t *testing.T) {
	root := t.TempDir()
	os.WriteFile(filepath.Join(root, File), nil, 0o644)
	deep := filepath.Join(root, "a", "b")
	os.MkdirAll(deep, 0o755)
	s, found, err := Find(deep, false, "/home")
	if err != nil || !found || s.Root != root || s.Global || s.IPMDir() != filepath.Join(root, ".ipm") {
		t.Errorf("got %+v %v %v", s, found, err)
	}
	none := t.TempDir()
	if s, found, _ := Find(none, false, "/home"); found || s.Root != none {
		t.Errorf("no ipm.toml: %+v %v", s, found)
	}
	home := t.TempDir()
	if s, found, _ := Find(deep, true, home); found || !s.Global || s.Root != filepath.Join(home, "global") {
		t.Errorf("-g: %+v %v", s, found)
	}
}

func TestPacksRoundTrip(t *testing.T) {
	root := t.TempDir()
	in := []Pack{
		{Name: "web", Items: []string{"skill:o/r:skills/b", "skill:o/r:skills/a"}},
		{Name: "csharp-sdlc", Description: `C# "lifecycle"`, Items: []string{"agent:o/r:agents/x.md"}},
	}
	if err := SavePacks(root, in); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(filepath.Join(root, File))
	want := `# ipm packs: each becomes a Claude Code plugin under .ipm/plugins/ when you run ` + "`ipm pack build`" + `.

[packs.csharp-sdlc]
description = "C# \"lifecycle\""
items = [
  "agent:o/r:agents/x.md",
]

[packs.web]
description = ""
items = [
  "skill:o/r:skills/b",
  "skill:o/r:skills/a",
]
`
	if string(data) != want {
		t.Errorf("ipm.toml:\n%s\nwant:\n%s", data, want)
	}
	got, err := LoadPacks(root)
	if err != nil || len(got) != 2 || got[0].Name != "csharp-sdlc" || got[0].Description != `C# "lifecycle"` || !reflect.DeepEqual(got[1].Items, in[0].Items) {
		t.Errorf("load: %+v %v", got, err)
	}
	if p, err := LoadPacks(t.TempDir()); err != nil || p != nil {
		t.Errorf("missing file: %v %v", p, err)
	}
}

