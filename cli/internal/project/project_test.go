func TestLockRoundTrip(t *testing.T) {
	dir := t.TempDir()
	in := map[string]LockItem{
		"skill:o/r:skills/a": {ID: "skill:o/r:skills/a", Type: "skill", Name: "a", Repo: "o/r", Path: "skills/a", SHA: strings.Repeat("a", 40)},
		"plugin:o/r#c":       {ID: "plugin:o/r#c", Type: "plugin", Name: "c", Repo: "o/r", Source: `{"source":"github","repo":"x/c","sha":"` + strings.Repeat("b", 40) + `"}`},
	}
	if err := SaveLock(dir, in); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(filepath.Join(dir, LockFile))
	if !strings.HasPrefix(string(data), "# Generated by `ipm install`") || strings.Index(string(data), "plugin:o/r#c") > strings.Index(string(data), "skill:o/r:skills/a") {
		t.Errorf("lock:\n%s", data)
	}
	got, err := LoadLock(dir)
	if err != nil || !reflect.DeepEqual(got, in) {
		t.Errorf("got %+v %v", got, err)
	}
	if l, err := LoadLock(t.TempDir()); err != nil || len(l) != 0 {
		t.Errorf("missing lock: %v %v", l, err)
	}
}

