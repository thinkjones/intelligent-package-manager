func TestReplayInstallsGascity(t *testing.T) {
	f, _, tmp := gascityFake(t)
	if err := f.run("install", "gascity", "kit", "-C", tmp, "--name", "k2"); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	if err := os.RemoveAll(filepath.Join(tmp, "k2")); err != nil {
		t.Fatal(err)
	}
	f.out.Reset()
	if err := f.run("install"); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	if _, err := os.Stat(filepath.Join(tmp, "k2", "pack.toml")); err != nil {
		t.Errorf("not redone: %v\n%s", err, f.out.String())
	}
	if !strings.Contains(f.out.String(), "✓ installed kit (gascity "+filepath.Join(tmp, "k2")+")") {
		t.Errorf("output:\n%s", f.out.String())
	}
}

