const gasHeader = "# generated by ipm — rewritten by ipm install gascity; do not edit"

// gascityFake is installFake built once; it also returns a fresh folder
// outside the project to install into.
func gascityFake(t *testing.T) (*fake, string, string) {
	t.Helper()
	f, root := installFake(t)
	if err := f.run("pack", "build"); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	tmp := t.TempDir()
	if r, err := filepath.EvalSymlinks(tmp); err == nil {
		tmp = r
	}
	f.calls, f.dirs = nil, nil
	f.out.Reset()
	return f, root, tmp
}

