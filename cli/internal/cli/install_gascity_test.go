func TestInstallGascityDryRun(t *testing.T) {
	f, root, tmp := gascityFake(t)
	before, _ := os.ReadFile(filepath.Join(root, project.File))
	if err := f.run("install", "gascity", "kit", "-C", tmp, "--dry-run"); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	out := f.out.String()
	for _, want := range []string{"would write " + filepath.Join(tmp, "kit") + "\n", "  pack.toml\n", "  skills/s1/SKILL.md\n", "  agents/reviewer/prompt.md\n", "skipped plugin:o/r#e"} {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
	if strings.Contains(out, "installed") || strings.Contains(out, "gc import") {
		t.Errorf("a dry run installs nothing:\n%s", out)
	}
	if _, err := os.Stat(filepath.Join(tmp, "kit")); err == nil {
		t.Error("a dry run wrote the folder")
	}
	if after, _ := os.ReadFile(filepath.Join(root, project.File)); string(after) != string(before) {
		t.Errorf("ipm.toml changed:\n%s", after)
	}
	if pnpmCalls(f) != 0 {
		t.Error("a dry run runs no pnpm")
	}

	// without a current build
	if err := os.Remove(filepath.Join(root, ".ipm", project.StampFile)); err != nil {
		t.Fatal(err)
	}
	err := f.run("install", "gascity", "kit", "-C", tmp, "--dry-run")
	if err == nil || !strings.Contains(err.Error(), "--dry-run needs a current build — run ipm pack build first") || pnpmCalls(f) != 0 {
		t.Errorf("got %v", err)
	}
}

func TestInstallGascityRefusesForeign(t *testing.T) {
	f, _, tmp := gascityFake(t)
	target := filepath.Join(tmp, "kit")
	write(t, filepath.Join(target, "pack.toml"), "[pack]\nname = \"mine\"\n")
	err := f.run("install", "gascity", "kit", "-C", tmp)
	var exit *ExitError
	if err == nil || errors.As(err, &exit) || !strings.Contains(err.Error(), "exists and was not written by ipm — use --force to replace it") {
		t.Fatalf("got %v", err)
	}
	if data, _ := os.ReadFile(filepath.Join(target, "pack.toml")); string(data) != "[pack]\nname = \"mine\"\n" {
		t.Errorf("folder changed: %s", data)
	}
	if err := f.run("install", "gascity", "kit", "-C", tmp, "--force"); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	if data, _ := os.ReadFile(filepath.Join(target, "pack.toml")); !strings.HasPrefix(string(data), gasHeader) {
		t.Errorf("not replaced: %s", data)
	}
}

