const gasHeader = "# generated by ipm — rewritten by ipm install gascity; do not edit"

// gascityFake is installFake built once; it also returns a fresh folder
// outside the project to install into.
func gascityFake(t *testing.T) (*fake, string, string) {
	t.Helper()
	f, root := installFake(t)
	if err := f.run("pack", "build"); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	tmp := t.TempDir()
	if r, err := filepath.EvalSymlinks(tmp); err == nil {
		tmp = r
	}
	f.calls, f.dirs = nil, nil
	f.out.Reset()
	return f, root, tmp
}

func TestInstallGascityWritesPack(t *testing.T) {
	f, _, tmp := gascityFake(t)
	if err := f.run("install", "gascity", "kit", "-C", tmp); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	data, err := os.ReadFile(filepath.Join(tmp, "kit", "pack.toml"))
	if err != nil || !strings.HasPrefix(string(data), gasHeader+"\n") {
		t.Fatalf("pack.toml %v:\n%s", err, data)
	}
	for _, rel := range []string{"skills/s1/SKILL.md", "agents/reviewer/prompt.md", "agents/reviewer/agent.toml"} {
		if _, err := os.Stat(filepath.Join(tmp, "kit", rel)); err != nil {
			t.Errorf("missing %s", rel)
		}
	}
	dir := filepath.Join(tmp, "kit")
	out := f.out.String()
	for _, want := range []string{
		"✓ installed kit (gascity " + dir + ")",
		"skipped plugin:o/r#e: external plugin",
		"Import it into a city:\n  gc import add " + dir + "\nor add to the city's pack.toml:\n  [imports.kit]\n  source = \"" + dir + "\"\n",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
}

func TestInstallGascityRecords(t *testing.T) {
	f, root, tmp := gascityFake(t)
	inside := filepath.Join(root, "out")
	os.MkdirAll(inside, 0o755)
	if err := f.run("install", "gascity", "kit", "-C", inside); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	data, _ := os.ReadFile(filepath.Join(root, project.File))
	if !strings.Contains(string(data), "[[packs.kit.installs]]\ntarget = \"gascity\"\npath = \"out\"\nname = \"kit\"\n") {
		t.Errorf("ipm.toml:\n%s", data)
	}
	f.out.Reset()
	if err := f.run("pack", "show", "kit"); err != nil || !strings.Contains(f.out.String(), "installed: gascity kit "+inside) {
		t.Errorf("show %v:\n%s", err, f.out.String())
	}

	// user scope
	if err := f.run("pack", "-g", "new", "gk"); err != nil {
		t.Fatal(err)
	}
	scope, _ := currentScope(f.system(), true)
	if err := f.run("install", "gascity", "-g", "gk", "-C", tmp); err != nil {
		t.Fatalf("%v\n%s", err, f.out.String())
	}
	got, err := loadInstalls(f.system(), scope)
	want := []installRecord{{"gk", project.Install{Target: "gascity", Path: tmp, Name: "gk"}}}
	if err != nil || !reflect.DeepEqual(got, want) {
		t.Errorf("got %+v %v", got, err)
	}
	if _, err := os.Stat(filepath.Join(f.env["IPM_HOME"], "installs.json")); err != nil {
		t.Error(err)
	}
}

