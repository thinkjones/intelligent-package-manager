package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// pnpmPinned is the pnpm ipm runs through npx when the pnpm on PATH is older
// than pnpmMajor. pnpm 12's custom fetchers (the { delegate } form) are what
// let ipm keep upstream files intact.
const (
	pnpmPinned = "pnpm@12.10.1"
	pnpmMajor  = 12
)

// pnpmCmd is how to run pnpm: the program, the arguments that precede pnpm's
// own, and the version that will run.
type pnpmCmd struct {
	name    string
	prefix  []string
	version string
}

// versionLine is the first line of output that is a version.
var versionLine = regexp.MustCompile(`(?m)^\d+\.\d+\.\d+\S*`)

func (p pnpmCmd) String() string {
	return strings.TrimSpace(p.name + " " + strings.Join(p.prefix, " "))
}

// findPnpm uses pnpm from PATH when it is new enough, else the pinned pnpm
// through npx.
func findPnpm(sys System) (pnpmCmd, error) {
	have, failed := "", ""
	if _, err := sys.LookPath("pnpm"); err == nil {
		out, err := sys.Output("", "pnpm", "--version")
		// pnpm (or corepack) may warn before printing the version.
		have = versionLine.FindString(out)
		if err != nil {
			failed = strings.TrimSpace(out)
		}
		if major, _ := strconv.Atoi(strings.SplitN(have, ".", 2)[0]); err == nil && major >= pnpmMajor {
			return pnpmCmd{name: "pnpm", version: have}, nil
		}
	}
	if _, err := sys.LookPath("npx"); err == nil {
		return pnpmCmd{name: "npx", prefix: []string{"-y", pnpmPinned}, version: strings.TrimPrefix(pnpmPinned, "pnpm@")}, nil
	}
	if failed != "" {
		return pnpmCmd{}, fmt.Errorf("`pnpm --version` failed: %s — fix pnpm, or install Node so ipm can run %s through npx", failed, pnpmPinned)
	}
	if have != "" {
		return pnpmCmd{}, fmt.Errorf("ipm needs pnpm %d or later (found %s) — upgrade it (`npm i -g pnpm@%d`), or install Node so ipm can run %s through npx", pnpmMajor, have, pnpmMajor, pnpmPinned)
	}
	return pnpmCmd{}, fmt.Errorf("ipm fetches sources with pnpm %d or later — install it (https://pnpm.io/installation) or Node (so ipm can run %s through npx)", pnpmMajor, pnpmPinned)
}

// pnpmfile is written into the sources project on every sync. Upstream repos
// are content, not code: never install their npm dependencies, and unpack
// GitHub archives as they are rather than re-packing them with npm's rules
// (package.json "files", .npmignore), which drop agent content — see
// docs/superpowers/specs/2026-10-09-ipm-design.md.
const pnpmfile = `// Generated by ipm sync — do not edit; it is rewritten on every sync.
const ROOT = "%ROOT%"
const codeload = /^https:\/\/codeload\.github\.com\/([^/]+)\/([^/]+)\/tar\.gz\/([0-9a-f]{40})/

module.exports = {
  hooks: {
    // Sources are content, not code: never install their npm dependencies.
    readPackage(pkg) {
      if (pkg.name !== ROOT) {
        // pnpm can't write a lockfile entry for a package without a name.
        if (!pkg.name) pkg.name = "unnamed"
        if (!pkg.version) pkg.version = "0.0.0"
        pkg.dependencies = {}
        pkg.optionalDependencies = {}
        pkg.peerDependencies = {}
      }
      return pkg
    },
  },
  // pnpm treats GitHub archives as git-hosted packages and re-packs them with
  // npm's rules; fetching the same commit as a plain tarball keeps every file.
  fetchers: [{
    canFetch: (pkgId, r) => !!(r && typeof r.tarball === "string" && codeload.test(r.tarball)),
    fetch: (cafs, r) => {
      const [, owner, repo, sha] = r.tarball.match(codeload)
      return { delegate: { tarball: "https://github.com/" + owner + "/" + repo + "/archive/" + sha + ".tar.gz" } }
    },
  }],
}
`

// writePnpmfile writes the hook file, exempting root (the sources project's
// own package name) from readPackage, and returns its path.
func writePnpmfile(dir, root string) (string, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(dir, ".pnpmfile.cjs")
	return path, os.WriteFile(path, []byte(strings.Replace(pnpmfile, "%ROOT%", root, 1)), 0o644)
}
