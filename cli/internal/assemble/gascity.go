// GasHeader is the first line of every file ipm writes into a Gas City
// pack; its presence marks a folder as ipm's to rewrite.
const GasHeader = "# generated by ipm — rewritten by ipm install gascity; do not edit"

// GasKind is what a Gas City pack entry is.
type GasKind string

// The entry kinds a Gas City pack can hold.
const (
	GasSkill GasKind = "skill"
	GasAgent GasKind = "agent"
	GasMCP   GasKind = "mcp"
)

// GasEntry is one skill, agent or MCP server in the folder. Item is the
// picked item, or for a part of a whole plugin a LockItem built from the
// part's ID with the plugin's repo and commit.
type GasEntry struct {
	Kind   GasKind
	Name   string // sanitised, unique within Kind
	Alias  string // node_modules folder (sources.Alias)
	From   string // repo-relative path: skill dir, agent .md, or MCP file
	Server string // MCP server key inside From
	Item   project.LockItem
}

// GascityPlan is what a pack becomes as a Gas City pack folder.
type GascityPlan struct {
	Name, Description string
	Picked            []project.LockItem // the pack's own items, for the header
	Entries           []GasEntry         // sorted by Kind, then Name
	Skips             []string           // "skipped <id>: …", in item order
}

var (
	gasNameRE    = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_-]*$`)
	gasUnsafe    = regexp.MustCompile(`[^a-z0-9_-]+`)
	gasMCPUnsafe = regexp.MustCompile(`[^a-z0-9-]+`)
)

// ValidGasName reports whether name can be a pack folder name.
func ValidGasName(name string) bool { return gasNameRE.MatchString(name) }

func gasSlug(s string) string {
	return strings.Trim(gasUnsafe.ReplaceAllString(strings.ToLower(s), "-"), "-_")
}

func gasMCPSlug(s string) string {
	return strings.Trim(gasMCPUnsafe.ReplaceAllString(strings.ToLower(s), "-"), "-")
}

// uniqueName claims base within key (a type or folder) in used: base if
// free, else base-<repo owner>, else base-2, base-3. clean sanitises the
// owner the way base was.
func uniqueName(used map[string]bool, key, base, repo string, clean func(string) string) string {
	name := base
	if used[key+"/"+name] {
		owner, _, _ := strings.Cut(pack.NormalizeRepo(repo), "/")
		name = base + "-" + clean(owner)
		for n := 2; used[key+"/"+name]; n++ {
			name = fmt.Sprintf("%s-%d", base, n)
		}
	}
	used[key+"/"+name] = true
	return name
}

const (
	skipCommand  = "skipped %s: Gas City has no slash commands"
	skipHook     = "skipped %s: Gas City packs have no hooks"
	skipExternal = "skipped %s: external plugin — its files live in another repo; add its skills and agents directly"
	skipNothing  = "skipped %s: nothing Gas City can hold"
	skipNoParts  = "skipped %s: its parts aren't recorded — run ipm pack build --update"
)

// PlanGascity decides the entries a pack gives a Gas City pack folder: its
// skills, agents and MCP servers (a whole plugin's parts included), their
// unique names, and what is skipped because Gas City has no equivalent.
func PlanGascity(p project.Pack, name string, items map[string]project.LockItem) (GascityPlan, error) {
	plan := GascityPlan{Name: name, Description: p.Description}
	used := map[string]bool{}
	placed := map[string]bool{}
	add := func(kind GasKind, base, server string, it project.LockItem) error {
		clean := gasSlug
		if kind == GasMCP {
			clean = gasMCPSlug
		}
		if placed[it.ID] {
			return nil
		}
		placed[it.ID] = true
		if base == "" {
			return fmt.Errorf("%s has no name usable as a folder name", it.ID)
		}
		plan.Entries = append(plan.Entries, GasEntry{Kind: kind, Name: uniqueName(used, string(kind), base, it.Repo, clean), Alias: sources.Alias(it.Repo), From: it.Path, Server: server, Item: it})
		return nil
	}
	named := func(it project.LockItem) string {
		if b := gasSlug(it.Name); b != "" {
			return b
		}
		return gasSlug(strings.TrimSuffix(path.Base(it.Path), ".md"))
	}
	for _, id := range p.Items {
		it, ok := items[id]
		if !ok {
			return GascityPlan{}, fmt.Errorf("%s is not resolved", id)
		}
		plan.Picked = append(plan.Picked, it)
		switch it.Type {
		case catalog.TypeSkill:
			if err := add(GasSkill, named(it), "", it); err != nil {
				return GascityPlan{}, err
			}
		case catalog.TypeAgent:
			if err := add(GasAgent, named(it), "", it); err != nil {
				return GascityPlan{}, err
			}
		case catalog.TypeCommand:
			plan.Skips = append(plan.Skips, fmt.Sprintf(skipCommand, it.ID))
		case catalog.TypeCopilotPlugin:
			skills, err := copilotSkills(it)
			if err != nil {
				return GascityPlan{}, fmt.Errorf("%s: %w", id, err)
			}
			for _, s := range skills {
				sk, ok := items[s]
				if !ok || sk.Type != catalog.TypeSkill {
					return GascityPlan{}, fmt.Errorf("%s lists %s, which is not a resolved skill", id, s)
				}
				if err := add(GasSkill, named(sk), "", sk); err != nil {
					return GascityPlan{}, err
				}
			}
		case catalog.TypePlugin:
			if it.Path == "" {
				plan.Skips = append(plan.Skips, fmt.Sprintf(skipExternal, it.ID))
				continue
			}
			if it.Parts == nil {
				plan.Skips = append(plan.Skips, fmt.Sprintf(skipNoParts, it.ID))
				continue
			}
			if len(it.Parts) == 0 {
				plan.Skips = append(plan.Skips, fmt.Sprintf(skipNothing, it.ID))
				continue
			}
			for _, part := range it.Parts {
				pi := partItem(it, part)
				var err error
				switch pi.Type {
				case catalog.TypeSkill:
					err = add(GasSkill, gasSlug(pi.Name), "", pi)
				case catalog.TypeAgent:
					err = add(GasAgent, gasSlug(pi.Name), "", pi)
				case catalog.TypeMCP:
					_, server := splitName(part)
					err = add(GasMCP, gasMCPSlug(server), server, pi)
				case catalog.TypeCommand:
					plan.Skips = append(plan.Skips, fmt.Sprintf(skipCommand, part))
				case catalog.TypeHook:
					plan.Skips = append(plan.Skips, fmt.Sprintf(skipHook, part))
				default:
					err = fmt.Errorf("%s: part %s is a %s, which Gas City packs can't hold", id, part, pi.Type)
				}
				if err != nil {
					return GascityPlan{}, err
				}
			}
		default:
			return GascityPlan{}, fmt.Errorf("%s is a %s; only skills, agents, commands and whole plugins can be picked — hooks and MCP servers come with their plugin", id, it.Type)
		}
	}
	rank := map[GasKind]int{GasSkill: 0, GasAgent: 1, GasMCP: 2}
	sort.SliceStable(plan.Entries, func(i, j int) bool {
		a, b := plan.Entries[i], plan.Entries[j]
		if a.Kind != b.Kind {
			return rank[a.Kind] < rank[b.Kind]
		}
		return a.Name < b.Name
	})
	return plan, nil
}

// splitName splits an ID's "#name" suffix off, returning the rest and name.
func splitName(id string) (rest, name string) {
	if i := strings.LastIndex(id, "#"); i >= 0 {
		return id[:i], id[i+1:]
	}
	return id, ""
}

// partItem is a plugin part (an item ID) as a LockItem in the plugin's repo
// at its commit; its path and name come from the ID.
func partItem(plugin project.LockItem, id string) project.LockItem {
	typ, rest, _ := strings.Cut(id, ":")
	rest = strings.TrimPrefix(rest, plugin.Repo+":")
	rest, name := splitName(rest)
	if name == "" {
		name = strings.TrimSuffix(path.Base(rest), ".md")
	}
	return project.LockItem{ID: id, Type: typ, Name: name, Repo: plugin.Repo, Path: rest, SHA: plugin.SHA}
}
