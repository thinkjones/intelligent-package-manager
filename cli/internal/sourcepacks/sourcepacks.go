// Package sourcepacks maintains source-packs.toml: the curated list ipm
// onboard offers, holding only repos with something ipm can catalog. Update
// finds the repos of a wider list (thinkjones/agentic-tools's
// starred_repos.toml) that aren't in it yet and scans each one; Report
// describes what it added. cmd/sourcepacks runs it; the Source packs
// workflow runs that by hand and opens a pull request.
package sourcepacks

import (
	"fmt"
	"net/url"
	"sort"
	"strings"
	"sync"

	"github.com/thinkjones/intelligent-package-manager/cli/internal/curated"
	"github.com/thinkjones/intelligent-package-manager/cli/internal/search"
)

// Kinds is what a scan counts, in report order, with the word for one.
var Kinds = []struct{ Key, One string }{
	{"plugins", "plugin"}, {"marketplaces", "marketplace"}, {"copilot_plugins", "Copilot plugin"},
	{"skills", "skill"}, {"agents", "agent"}, {"commands", "command"}, {"hooks", "hooks file"}, {"mcp", "MCP file"},
}

// Scan counts what ipm would catalog in repo, by kind. A repo holding
// nothing gives an empty map; an error means it couldn't be read. Update
// keeps a repo that holds anything other than MCP files.
type Scan func(repo string) (map[string]int, error)

// Failure is a repo that couldn't be scanned. It is recorded nowhere, so the
// next run tries it again.
type Failure struct {
	Repo string
	Err  error
}

// Result is what Update decided.
type Result struct {
	Packs   []curated.List // every pack, with the new repos in place
	Added   []curated.List // only the new repos, under their packs
	Skipped []string       // every repo known to hold nothing, sorted
	Failed  []Failure
	Scanned int
}

// StarredURL is the wider list new repos are looked for in.
const StarredURL = "https://raw.githubusercontent.com/thinkjones/agentic-tools/main/starred_repos.toml"

// Header opens source-packs.toml.
const Header = `Source packs: the repos ipm onboard offers, grouped into named lists.
Every repo here holds something ipm can catalog; artifacts counts what.
Generated by "mise run packs:update" from thinkjones/agentic-tools's
starred_repos.toml. Do not edit by hand: change that list, or the task.`

const skippedHeader = `# Repos of starred_repos.toml found to hold nothing ipm can catalog, so
# "mise run packs:update" doesn't fetch them again. Pass --recheck to do so.
# Generated; do not edit by hand.
`

// ParseSkipped reads a skipped file: one owner/repo per line, # comments.
func ParseSkipped(data []byte) []string {
	var out []string
	for _, line := range strings.Split(string(data), "\n") {
		if line = strings.TrimSpace(line); line != "" && !strings.HasPrefix(line, "#") {
			out = append(out, line)
		}
	}
	return out
}

// EncodeSkipped writes a skipped file.
func EncodeSkipped(repos []string) []byte {
	return []byte(skippedHeader + strings.Join(repos, "\n") + "\n")
}

func key(list, repo string) string { return list + "\x00" + strings.ToLower(repo) }

// Update adds to packs each repo of starred that isn't there yet and holds
// something. A repo in skipped isn't scanned again unless recheck is set; a
// repo already in a pack isn't scanned to join another. Packs keep their
// order, new ones follow in starred's order, and the stars, description and
// other details of repos still in starred are refreshed from it.
func Update(starred, packs []curated.List, skipped []string, recheck bool, scan Scan, workers int) Result {
	skip := map[string]bool{}
	for _, r := range skipped {
		skip[strings.ToLower(r)] = true
	}
	fresh := map[string]curated.Repo{}
	for _, l := range starred {
		for _, r := range l.Repos {
			fresh[key(l.Name, r.Repo)] = r
		}
	}
	artifacts := map[string]map[string]int{}
	have := map[string]bool{}
	var out []curated.List
	for _, l := range packs {
		nl := curated.List{Name: l.Name}
		for _, r := range l.Repos {
			if f, ok := fresh[key(l.Name, r.Repo)]; ok {
				f.Artifacts = r.Artifacts
				r = f
			}
			have[key(l.Name, r.Repo)] = true
			artifacts[strings.ToLower(r.Repo)] = r.Artifacts
			nl.Repos = append(nl.Repos, r)
		}
		out = append(out, nl)
	}

	var todo []string
	queued := map[string]bool{}
	for _, l := range starred {
		for _, r := range l.Repos {
			k := strings.ToLower(r.Repo)
			if have[key(l.Name, r.Repo)] || queued[k] || (skip[k] && !recheck) {
				continue
			}
			if _, known := artifacts[k]; known {
				continue
			}
			queued[k] = true
			todo = append(todo, r.Repo)
		}
	}
	res := Result{Scanned: len(todo)}
	failed := map[string]bool{}
	type scanned struct {
		counts map[string]int
		err    error
	}
	results := make([]scanned, len(todo))
	var wg sync.WaitGroup
	sem := make(chan struct{}, max(workers, 1))
	for i, repo := range todo {
		wg.Add(1)
		go func() {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			results[i].counts, results[i].err = scan(repo)
		}()
	}
	wg.Wait()
	for i, repo := range todo {
		k := strings.ToLower(repo)
		switch r := results[i]; {
		case r.err != nil:
			// not skipped any more, so a failed recheck is tried again too
			failed[k] = true
			delete(skip, k)
			res.Failed = append(res.Failed, Failure{repo, r.err})
		case !Qualifies(r.counts):
			skip[k] = true
		default:
			delete(skip, k)
			artifacts[k] = r.counts
		}
	}

	at := map[string]int{}
	for i, l := range out {
		at[l.Name] = i
	}
	addedAt := map[string]int{}
	for _, l := range starred {
		for _, r := range l.Repos {
			k := strings.ToLower(r.Repo)
			if have[key(l.Name, r.Repo)] || skip[k] || failed[k] {
				continue
			}
			have[key(l.Name, r.Repo)] = true
			r.Artifacts = artifacts[k]
			i, ok := at[l.Name]
			if !ok {
				i = len(out)
				at[l.Name] = i
				out = append(out, curated.List{Name: l.Name})
			}
			out[i].Repos = append(out[i].Repos, r)
			j, ok := addedAt[l.Name]
			if !ok {
				j = len(res.Added)
				addedAt[l.Name] = j
				res.Added = append(res.Added, curated.List{Name: l.Name})
			}
			res.Added[j].Repos = append(res.Added[j].Repos, r)
		}
	}
	for _, ls := range [][]curated.List{out, res.Added} {
		for _, l := range ls {
			sort.SliceStable(l.Repos, func(a, b int) bool {
				if l.Repos[a].Stars != l.Repos[b].Stars {
					return l.Repos[a].Stars > l.Repos[b].Stars
				}
				return l.Repos[a].Repo < l.Repos[b].Repo
			})
		}
	}
	res.Packs = out
	for k := range skip {
		res.Skipped = append(res.Skipped, k)
	}
	sort.Strings(res.Skipped)
	return res
}

// Qualifies reports whether counts hold something worth following a repo
// for. An MCP file alone doesn't count: most are a repo's own development
// setup, and an MCP server can't be picked into a pack.
func Qualifies(counts map[string]int) bool {
	for kind, n := range counts {
		if kind != "mcp" && n > 0 {
			return true
		}
	}
	return false
}

// Holds says what counts hold, as "14 skills, 1 plugin".
func Holds(counts map[string]int) string {
	var parts []string
	for _, k := range Kinds {
		switch n := counts[k.Key]; {
		case n == 1:
			parts = append(parts, "1 "+k.One)
		case n > 1:
			parts = append(parts, fmt.Sprintf("%d %ss", n, k.One))
		}
	}
	return strings.Join(parts, ", ")
}

// Count is how many repos lists hold, each list's rows counted.
func Count(lists []curated.List) int {
	n := 0
	for _, l := range lists {
		n += len(l.Repos)
	}
	return n
}

// Report is the Markdown summary of a run: the new repos under their packs,
// each with its stars, description, topics, homepage and what it holds, then
// the repos that couldn't be scanned.
func Report(res Result) string {
	var b strings.Builder
	if n := Count(res.Added); n == 0 {
		b.WriteString("## No new repos for the source packs\n")
	} else {
		fmt.Fprintf(&b, "## %d new %s in %d source %s\n", n, plural(n, "repo"), len(res.Added), plural(len(res.Added), "pack"))
	}
	fmt.Fprintf(&b, "\nScanned %d %s; %d hold nothing ipm can catalog so far.\n", res.Scanned, plural(res.Scanned, "repo"), len(res.Skipped))
	for _, l := range res.Added {
		fmt.Fprintf(&b, "\n### %s (%d)\n\n", l.Name, len(l.Repos))
		for _, r := range l.Repos {
			fmt.Fprintf(&b, "- **[%s](https://github.com/%s)** ★ %s", r.Repo, r.Repo, search.Stars(r.Stars))
			if r.Description != "" {
				fmt.Fprintf(&b, " — %s", plain(r.Description))
			}
			b.WriteString("\n")
			if len(r.Topics) > 0 {
				topics := make([]string, len(r.Topics))
				for i, t := range r.Topics {
					topics[i] = plain(t)
				}
				fmt.Fprintf(&b, "  - topics: %s\n", strings.Join(topics, ", "))
			}
			if u, err := url.Parse(r.Homepage); err == nil && (u.Scheme == "http" || u.Scheme == "https") && u.Host != "" && !strings.ContainsAny(r.Homepage, "<> \t\r\n") {
				fmt.Fprintf(&b, "  - homepage: <%s>\n", r.Homepage)
			} else if r.Homepage != "" {
				fmt.Fprintf(&b, "  - homepage: %s\n", plain(r.Homepage))
			}
			fmt.Fprintf(&b, "  - holds: %s\n", Holds(r.Artifacts))
		}
	}
	if len(res.Failed) > 0 {
		fmt.Fprintf(&b, "\n### Couldn't be scanned (%d)\n\nThese are tried again on the next run.\n\n", len(res.Failed))
		for _, f := range res.Failed {
			fmt.Fprintf(&b, "- `%s`: %v\n", f.Repo, f.Err)
		}
	}
	return b.String()
}

// plain writes a repo's own words (its description, a topic) so Markdown
// shows them and does nothing else: on one line, with nothing read as
// formatting, a link, an image or HTML, and with a zero-width space after #
// and @ so "Fixes #12" closes no issue and "@name" notifies no one.
func plain(s string) string {
	var b strings.Builder
	for _, r := range strings.Join(strings.Fields(s), " ") {
		switch {
		case r == '#' || r == '@':
			b.WriteRune(r)
			b.WriteRune('\u200b')
		case strings.ContainsRune("\\`*_[]()<>!|~&", r):
			b.WriteByte('\\')
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f:
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func plural(n int, word string) string {
	if n == 1 {
		return word
	}
	return word + "s"
}
