// Package upstream keeps a local cache of every repo the packs read from,
// pinned to the commits recorded in aihs.lock.
//
// Versions follow npm's git-dependency convention. A manifest asks for a
// version — a tag, branch or commit, or nothing for the default branch — and
// aihs.lock records the commit it resolved to, as package-lock records
// `resolved`. The lock is committed, so every marketplace entry is published
// at a known commit and upgrading is deliberate (`ipm sync --upgrade`).
//
// The cache is <root>/.aihs/cache/<owner>/<repo>/<commit>/ — inside the
// checkout, gitignored — one shallow checkout per locked commit. It is keyed
// by commit rather than by tag or branch because a commit cannot move: the
// same folder always holds the same files. Sync fetches only commits it does
// not hold and prunes the ones no longer locked.
package upstream

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"

	"github.com/BurntSushi/toml"

	"github.com/thinkjones/fs-skills/cli/internal/pack"
)

// LockFile is the lock's name at the checkout root.
const LockFile = "aihs.lock"

// Git runs git with args in dir and returns its combined output.
type Git func(dir string, args ...string) (string, error)

var (
	shaRE      = regexp.MustCompile(`^[0-9a-f]{40}$`)
	ownerRepo  = regexp.MustCompile(`^[\w.-]+/[\w.-]+$`)
	scheme     = regexp.MustCompile(`^([a-z+]+://|[^@/]+@)`)
	unsafeChar = regexp.MustCompile(`[^A-Za-z0-9._-]+`)
)

// IsSHA reports whether version is a full commit SHA.
func IsSHA(version string) bool { return shaRE.MatchString(version) }

// CloneURL is what git fetches for repo: GitHub for owner/repo, else as given.
func CloneURL(repo string) string {
	if ownerRepo.MatchString(repo) {
		return "https://github.com/" + repo + ".git"
	}
	return repo
}

// CacheRoot is the directory holding every cached upstream.
func CacheRoot(root string) string { return filepath.Join(root, ".aihs", "cache") }

// repoPath is repo as cache folders: owner/repo for GitHub, else the URL's
// host and path ("gitlab.com/group/project"), each segment made path-safe.
func repoPath(repo string) string {
	if !ownerRepo.MatchString(repo) {
		repo = strings.TrimSuffix(scheme.ReplaceAllString(repo, ""), ".git")
		repo = strings.ReplaceAll(repo, ":", "/")
	}
	var parts []string
	for _, seg := range strings.Split(repo, "/") {
		if seg = strings.Trim(unsafeChar.ReplaceAllString(seg, "_"), "_."); seg != "" {
			parts = append(parts, seg)
		}
	}
	return filepath.Join(parts...)
}

// Dir is the cached checkout of repo at commit.
func Dir(root, repo, commit string) string {
	return filepath.Join(CacheRoot(root), repoPath(repo), commit)
}

// Lock maps an upstream key (repo@version) to its locked commit.
type Lock map[string]string

type lockFile struct {
	Repo []struct {
		Repo    string `toml:"repo"`
		Version string `toml:"version"`
		Commit  string `toml:"commit"`
	} `toml:"repo"`
}

// ReadLock reads aihs.lock; a missing file is an empty lock.
func ReadLock(root string) (Lock, error) {
	path := filepath.Join(root, LockFile)
	var f lockFile
	if _, err := toml.DecodeFile(path, &f); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return Lock{}, nil
		}
		return nil, fmt.Errorf("%s: %v", path, err)
	}
	lock := Lock{}
	for _, r := range f.Repo {
		lock[pack.Upstream{Repo: r.Repo, Version: r.Version}.Key()] = r.Commit
	}
	return lock, nil
}

// WriteLock writes the commits for ups, sorted by key.
func WriteLock(root string, lock Lock, ups []pack.Upstream) error {
	sorted := append([]pack.Upstream(nil), ups...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Key() < sorted[j].Key() })
	var b strings.Builder
	b.WriteString("# Generated by `ipm sync` — commit it. Each upstream's requested version\n")
	b.WriteString("# (default branch when omitted) and the commit it resolved to.\n")
	b.WriteString("# `ipm sync --upgrade` re-resolves every version.\n")
	for _, u := range sorted {
		commit, ok := lock[u.Key()]
		if !ok {
			continue
		}
		fmt.Fprintf(&b, "\n[[repo]]\nrepo = %q\n", u.Repo)
		if u.Version != "" {
			fmt.Fprintf(&b, "version = %q\n", u.Version)
		}
		fmt.Fprintf(&b, "commit = %q\n", commit)
	}
	return os.WriteFile(filepath.Join(root, LockFile), []byte(b.String()), 0o644)
}

// Missing is every upstream in ups the lock does not pin.
func (l Lock) Missing(ups []pack.Upstream) []pack.Upstream {
	var out []pack.Upstream
	for _, u := range ups {
		if l[u.Key()] == "" {
			out = append(out, u)
		}
	}
	return out
}

// Checkout is u's cached checkout at its locked commit, verified, so anything
// read from it matches what the marketplace publishes.
func Checkout(root string, u pack.Upstream, lock Lock) (string, error) {
	want := lock[u.Key()]
	if want == "" {
		return "", fmt.Errorf("%s does not pin %s — run `ipm sync`", LockFile, u.Key())
	}
	dir := Dir(root, u.Repo, want)
	if head(dir) != want {
		return "", fmt.Errorf("the cache does not hold %s at its locked commit %s — run `ipm sync`", u.Key(), want[:7])
	}
	return dir, nil
}

// head is the commit a cached checkout is at; a detached checkout's HEAD file
// holds it directly. "" when there is no checkout.
func head(dir string) string {
	data, err := os.ReadFile(filepath.Join(dir, ".git", "HEAD"))
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(data))
}

// Result is what Sync did with one upstream.
type Result struct {
	Upstream pack.Upstream
	Commit   string
	// Was is the previously locked commit, when it changed.
	Was string
	// Fetched is false when the cache already held the commit.
	Fetched bool
	Err     error
}

// Sync brings the cache and lock in line with ups and returns the new lock.
// A locked upstream stays at its commit unless upgrade; a failure keeps that
// upstream's previous commit. Cached commits no longer locked are removed.
//
// It runs in two phases — resolve every upstream's commit, then fetch each
// distinct repo-and-commit once — because two versions (a tag and a branch,
// say) can resolve to the same commit and so share one cached checkout.
func Sync(git Git, root string, ups []pack.Upstream, lock Lock, upgrade bool) ([]Result, Lock) {
	results := make([]Result, len(ups))
	parallel(len(ups), func(i int) { results[i] = target(git, root, ups[i], lock[ups[i].Key()], upgrade) })

	type checkout struct{ repo, commit string }
	var todo []checkout
	firstFor := map[checkout]int{}
	for i, r := range results {
		c := checkout{r.Upstream.Repo, r.Commit}
		if r.Err != nil || head(Dir(root, c.repo, c.commit)) == c.commit {
			continue
		}
		if _, seen := firstFor[c]; !seen {
			firstFor[c] = i
			todo = append(todo, c)
		}
	}
	errs := make([]error, len(todo))
	parallel(len(todo), func(i int) { errs[i] = fetch(git, root, todo[i].repo, todo[i].commit) })
	for i, c := range todo {
		results[firstFor[c]].Fetched = true
		for j := range results {
			if results[j].Err == nil && (checkout{results[j].Upstream.Repo, results[j].Commit}) == c {
				results[j].Err = errs[i]
			}
		}
	}

	next := Lock{}
	for _, r := range results {
		switch {
		case r.Err == nil:
			next[r.Upstream.Key()] = r.Commit
		case lock[r.Upstream.Key()] != "":
			next[r.Upstream.Key()] = lock[r.Upstream.Key()]
		}
	}
	keep := map[string]bool{}
	for _, u := range ups {
		if c := next[u.Key()]; c != "" {
			keep[Dir(root, u.Repo, c)] = true
		}
	}
	prune(CacheRoot(root), keep)
	return results, next
}

// Ensure caches u without writing the lock or pruning anything: at its locked
// commit when pinned, else the remote's current commit for its version. An
// unpinned upstream's checkout lasts until the next Sync prunes it.
func Ensure(git Git, root string, u pack.Upstream, lock Lock) (dir string, fetched bool, err error) {
	r := target(git, root, u, lock[u.Key()], false)
	if r.Err != nil {
		return "", false, r.Err
	}
	dir = Dir(root, u.Repo, r.Commit)
	if head(dir) == r.Commit {
		return dir, false, nil
	}
	if err := fetch(git, root, u.Repo, r.Commit); err != nil {
		return "", false, err
	}
	return dir, true, nil
}

// parallel runs fn for 0..n-1, four at a time.
func parallel(n int, fn func(int)) {
	var wg sync.WaitGroup
	sem := make(chan struct{}, 4)
	for i := range n {
		wg.Go(func() {
			sem <- struct{}{}
			defer func() { <-sem }()
			fn(i)
		})
	}
	wg.Wait()
}

// target decides the commit u should be at: its version when that is a
// commit, else the locked commit, else (or when upgrading) the remote's.
func target(git Git, root string, u pack.Upstream, locked string, upgrade bool) Result {
	r := Result{Upstream: u, Commit: locked}
	switch {
	case IsSHA(u.Version):
		r.Commit = u.Version
	case upgrade || locked == "":
		commit, err := resolve(git, root, u)
		if err != nil {
			r.Err = err
			return r
		}
		r.Commit = commit
	}
	if locked != "" && locked != r.Commit {
		r.Was = locked
	}
	return r
}

// fetch makes Dir(root, repo, commit) a shallow checkout of that commit.
func fetch(git Git, root, repo, commit string) error {
	dir := Dir(root, repo, commit)
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, args := range [][]string{
		{"-C", dir, "init", "-q"},
		{"-C", dir, "fetch", "-q", "--depth", "1", CloneURL(repo), commit},
		{"-C", dir, "checkout", "-q", "-f", "--detach", "FETCH_HEAD"},
	} {
		if out, err := git(root, args...); err != nil {
			os.RemoveAll(dir)
			return fmt.Errorf("git %s: %v: %s", args[2], err, strings.TrimSpace(out))
		}
	}
	return nil
}

// resolve asks the remote which commit u's version (or its default branch)
// is at.
func resolve(git Git, root string, u pack.Upstream) (string, error) {
	ref := u.Version
	if ref == "" {
		ref = "HEAD"
	}
	// Ask for the peeled form too: an annotated tag's own sha is not a commit.
	out, err := git(root, "ls-remote", CloneURL(u.Repo), ref, ref+"^{}")
	if err != nil {
		return "", fmt.Errorf("git ls-remote %s: %v: %s", u.Repo, err, strings.TrimSpace(out))
	}
	var found string
	for line := range strings.SplitSeq(strings.TrimSpace(out), "\n") {
		fields := strings.Fields(line)
		if len(fields) != 2 || !IsSHA(fields[0]) {
			continue
		}
		switch fields[1] {
		case "HEAD", "refs/heads/" + ref, "refs/tags/" + ref:
			if found == "" {
				found = fields[0]
			}
		case "refs/tags/" + ref + "^{}":
			found = fields[0]
		}
	}
	if found == "" {
		return "", fmt.Errorf("%s has no version %q", u.Repo, ref)
	}
	return found, nil
}

// prune removes every cached checkout under cacheRoot not in keep, then the
// folders that leaves empty.
func prune(cacheRoot string, keep map[string]bool) {
	var checkouts []string
	filepath.WalkDir(cacheRoot, func(path string, d fs.DirEntry, err error) error {
		if err != nil || !d.IsDir() {
			return nil
		}
		if _, err := os.Stat(filepath.Join(path, ".git")); err == nil {
			checkouts = append(checkouts, path)
			return filepath.SkipDir
		}
		return nil
	})
	for _, c := range checkouts {
		if !keep[c] {
			os.RemoveAll(c)
		}
	}
	// Remove emptied folders, deepest first.
	var dirs []string
	filepath.WalkDir(cacheRoot, func(path string, d fs.DirEntry, err error) error {
		if err == nil && d.IsDir() && path != cacheRoot {
			dirs = append(dirs, path)
		}
		return nil
	})
	sort.Slice(dirs, func(i, j int) bool { return len(dirs[i]) > len(dirs[j]) })
	for _, d := range dirs {
		os.Remove(d) // fails, harmlessly, unless empty
	}
}
